import { test, expect } from '@playwright/test';
import fs from 'node:fs';
import path from 'node:path';

test('dense default, full real capture, camera controls and sparse-mode recovery', async ({ page }) => {
  test.setTimeout(240000);
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', e => { if (e.type() === 'error') errors.push(e.text()); });
  await page.goto('/');
  await page.locator('.file-select').filter({ hasText: '2.pcap' }).first().click();
  await expect(page.getByLabel('叠加帧数')).toHaveValue('200');
  await expect(page.getByLabel('渲染点数上限')).toHaveValue('0');
  await expect(page.locator('.canvas-meta')).toContainText('200 帧叠加', { timeout: 60000 });
  await expect(page.locator('.loading-frame')).toHaveCount(0);
  await page.waitForTimeout(1200);
  const defaultCount = await page.getByTestId('point-count').textContent();
  expect(defaultCount).toContain('原始 4,000,000 点');
  await page.screenshot({ path: path.resolve('../test-results/dense-default.png') });
  const defaultFPS = Number(await page.getByTestId('fps').textContent());
  await page.getByTitle('放大', { exact: true }).click();
  await page.getByTitle('缩小', { exact: true }).click();
  await page.getByRole('button', { name: '旋转', exact: true }).click();
  const canvas = page.locator('.cloud-canvas canvas');
  const box = (await canvas.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 150, box.y + box.height / 2 + 50, { steps: 20 });
  await page.mouse.up();
  await canvas.press('f');
  await page.getByRole('button', { name: '平移', exact: true }).click();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 80, box.y + box.height / 2, { steps: 10 });
  await page.mouse.up();
  await page.getByTitle('聚焦主体（F）', { exact: true }).click();
  const started = performance.now();
  await page.getByRole('button', { name: '加载整包全部点', exact: true }).click();
  await expect(page.locator('.canvas-meta')).toContainText('1534 帧叠加', { timeout: 150000 });
  await expect(page.locator('.loading-frame')).toHaveCount(0);
  await page.waitForTimeout(1500);
  const fullCount = await page.getByTestId('point-count').textContent();
  expect(fullCount).toContain('原始 30,675,400 点');
  const fullFPS = Number(await page.getByTestId('fps').textContent());
  await page.getByTitle('聚焦主体（F）', { exact: true }).click();
  await page.screenshot({ path: path.resolve('../test-results/dense-full.png') });
  await page.locator('.viewport').screenshot({ path: path.resolve('../test-results/dense-full-cloud.png') });
  const loadSeconds = (performance.now() - started) / 1000;
  await page.getByRole('button', { name: '正视', exact: true }).click();
  await page.screenshot({ path: path.resolve('../test-results/dense-full-front.png') });
  await page.getByRole('button', { name: '俯视', exact: true }).click();
  await page.screenshot({ path: path.resolve('../test-results/dense-full-top.png') });
  await page.getByRole('button', { name: '反射率', exact: true }).click();
  await expect(page.locator('.legend')).toContainText('反射率');
  // Playback preserves density instead of collapsing back to sparse single frames.
  await page.getByTitle('播放', { exact: true }).click();
  await expect(page.getByLabel('叠加帧数')).toHaveValue('200');
  await page.waitForTimeout(3000);
  await page.getByTitle('暂停', { exact: true }).click();
  expect(Number(await page.getByLabel('回放时间轴').inputValue())).toBeGreaterThan(15);
  await expect(page.getByTestId('point-count')).toContainText('原始 4,000,000 点');
  await page.getByLabel('回放时间轴').fill('1533');
  await expect(page.locator('.canvas-meta')).toContainText('不完整帧');
  await page.locator('.file-select').filter({ hasText: '1.pcap' }).first().click();
  await page.getByTitle('重置显示设置').click();
  await expect(page.locator('.canvas-meta')).toContainText('200 帧叠加', { timeout: 60000 });
  await expect(page.getByTestId('point-count')).toContainText('原始 4,000,000 点');
  await page.screenshot({ path: path.resolve('../test-results/dense-file1.png') });
  fs.writeFileSync(path.resolve('../test-results/density-metrics.json'), JSON.stringify({ defaultCount, defaultFPS, fullCount, fullFPS, loadSeconds, errors }, null, 2));
  expect(errors).toEqual([]);
});
